#!/bin/bash
# PM2 Conductor - Escalation Functions
# Handles Level 3 escalations: GitHub issues, notifications

GITHUB_REPO="${ESCALATION_GITHUB_REPO:-arwoxbx24/claude-state}"
REDIS_DB="${CONDUCTOR_REDIS_DB:-3}"
LOG_FILE="/root/workspaces/tools/acc1-scripts/logs/conductor.log"

# Log to file
log_event() {
  local level=$1
  local message=$2
  echo "[$(date -Iseconds)] [$level] $message" >> "$LOG_FILE"
}

# Create GitHub issue for critical errors
create_github_issue() {
  local app_name=$1
  local error_summary=$2
  local error_log=$3

  local body=$(cat <<EOF
## 🚨 PM2 Conductor Alert

**Process:** \`$app_name\`
**Time:** $(date -Iseconds)
**Server:** $(hostname)

### Error Summary
$error_summary

### Last 50 Log Lines
\`\`\`
$error_log
\`\`\`

### Auto-Fix Attempts
$(redis-cli -n $REDIS_DB LRANGE "conductor:fixes:$app_name" 0 4 2>/dev/null | tr '\n' '\n' || echo "None recorded")

---
*Generated by PM2 Conductor*
EOF
)

  # Create issue
  local issue_url=$(gh issue create \
    --repo "$GITHUB_REPO" \
    --title "🚨 PM2: $app_name crashed - manual fix needed" \
    --body "$body" \
    --label "auto-generated,pm2-conductor,priority-high" 2>&1)

  if [ $? -eq 0 ]; then
    log_event "INFO" "Created GitHub issue: $issue_url"
    echo "$issue_url"
    return 0
  else
    log_event "ERROR" "Failed to create GitHub issue: $issue_url"
    return 1
  fi
}

# Notify active Claude session (if exists)
notify_active_session() {
  local message=$1
  local notify_file="/tmp/claude-conductor-notify"

  # Check if any claude process is running
  if pgrep -x "claude" >/dev/null 2>&1; then
    echo "[CONDUCTOR $(date +%H:%M)] $message" >> "$notify_file"
    log_event "INFO" "Notified active session: $message"
    return 0
  else
    log_event "WARN" "No active Claude session to notify"
    return 1
  fi
}

# Create Redis task for agent pickup
create_fix_task() {
  local app_name=$1
  local error=$2
  local priority=${3:-high}

  local task=$(cat <<EOF
{
  "type": "pm2_fix",
  "app": "$app_name",
  "error": "$(echo "$error" | head -5 | tr '\n' ' ' | sed 's/"/\\"/g')",
  "priority": "$priority",
  "created": "$(date -Iseconds)",
  "status": "pending"
}
EOF
)

  redis-cli -n $REDIS_DB LPUSH "conductor:tasks" "$task" >/dev/null
  redis-cli -n $REDIS_DB EXPIRE "conductor:tasks" 604800 >/dev/null  # 7 days

  log_event "INFO" "Created fix task for $app_name"
}

# Full escalation sequence
escalate() {
  local app_name=$1
  local error_summary=$2
  local error_log=$3

  log_event "WARN" "Escalating issue for $app_name"

  # 1. Notify active session
  notify_active_session "⚠️ URGENT: $app_name needs attention"

  # 2. Create task in Redis
  create_fix_task "$app_name" "$error_summary" "critical"

  # 3. Create GitHub issue
  create_github_issue "$app_name" "$error_summary" "$error_log"

  # 4. Stop auto-restart to prevent damage loop
  pm2 stop "$app_name" --silent 2>/dev/null
  log_event "WARN" "Stopped $app_name to prevent damage"
}

export -f log_event create_github_issue notify_active_session create_fix_task escalate
